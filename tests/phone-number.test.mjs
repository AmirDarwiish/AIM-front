import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=readFileSync(new URL('../lib/phone-number.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {normalizeContactPhone:phone,splitInternationalPhone:split}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
assert.equal(phone('010 1234 5678','eg'),'+201012345678');
assert.equal(phone('٠١٠١٢٣٤٥٦٧٨','eg'),'+201012345678');
assert.equal(phone('۰۱۰۱۲۳۴۵۶۷۸','eg'),'+201012345678');
assert.equal(phone('+20 (10) 1234-5678','eg'),'+201012345678');
assert.equal(phone('00201012345678','eg'),'+201012345678');
assert.equal(phone('050 123 4567','sa'),'+966501234567');
assert.equal(phone('+971501234567','eg'),'+971501234567');
assert.equal(split('+971501234567').country.id,'ae');
assert.equal(phone('91234567','om'),'+96891234567');
assert.equal(phone('07123 456789','gb'),'+447123456789');
assert.equal(phone('2025550123','us'),'+12025550123');
for(const value of ['123','abc1234567','+2010123456789999','+999123456789','01012345678 ext 2'])assert.equal(phone(value,'eg'),null,value);
assert.equal(phone('01012345678','invalid'),null);
console.log('PASS: country codes, national prefixes, Arabic/Persian digits, pasted international numbers and invalid input.');
